def add_train_args(parser):
    # Dataset parameters
    parser.add_argument('--task', help='Task name')
    parser.add_argument('--split_method', default='random',
        choices=['random', 'protein', 'drug', 'both', 'seqid', 'fixed'],
        help='Split method: random, protein, drug, both, seqid, or fixed')
    parser.add_argument('--seed', type=int, default=42,
        help='Random Seed')
    parser.add_argument('--pdbbind_dir', default='../data/PDBbind',
        help='PDBbind directory containing processed manifest or source archives')
    parser.add_argument('--pdbbind_manifest',
        help='PDBbind PL manifest TSV generated by scripts/prepare_pdbbind_pl.py')
    parser.add_argument('--split_file',
        help='Fixed split TSV with columns: complex_id, split')
    parser.add_argument('--limit', type=int,
        help='Limit dataset rows for smoke tests')

    # Data representation parameters
    parser.add_argument('--contact_cutoff', type=float, default=8.,
        help='cutoff of C-alpha distance to define protein contact graph')
    parser.add_argument('--num_pos_emb', type=int, default=16,
        help='number of positional embeddings')
    parser.add_argument('--num_rbf', type=int, default=16,
        help='number of RBF kernels')

    # Protein model parameters
    parser.add_argument('--prot_gcn_dims', type=int, nargs='+', default=[128, 256, 256],
        help='protein GCN layers dimensions')
    parser.add_argument('--prot_fc_dims', type=int, nargs='+', default=[1024, 128],
        help='protein FC layers dimensions')

    # Drug model parameters
    parser.add_argument('--drug_gcn_dims', type=int, nargs='+', default=[128, 64],
        help='drug GVP hidden layers dimensions')
    parser.add_argument('--drug_fc_dims', type=int, nargs='+', default=[1024, 128],
        help='drug FC layers dimensions')

    # Optional GerNA-style protein 1D/2D + ligand 2D interaction branch
    parser.add_argument('--use_one_d_two_d', action='store_true',
        help='enable protein 1D/2D and ligand 2D pair-interaction branch')
    parser.add_argument('--one_d_two_d_protein_edge_cutoff', type=float, default=8.0,
        help='C-alpha distance cutoff for the protein 2D graph inside the 1D2D branch')
    parser.add_argument('--one_d_two_d_max_protein_residues', type=int, default=128,
        help='maximum nearest-to-ligand residues kept by the 1D2D branch; <=0 keeps all residues')
    parser.add_argument('--one_d_two_d_hidden_dim', type=int, default=64,
        help='hidden channel size for the 1D2D branch')
    parser.add_argument('--one_d_two_d_output_dim', type=int, default=128,
        help='raw output embedding dimension of the 1D2D branch')
    parser.add_argument('--one_d_two_d_gnn_layers', type=int, default=3,
        help='number of GNN layers used in the 1D2D branch')
    parser.add_argument('--one_d_two_d_triangle_layers', type=int, default=2,
        help='number of triangle pair-update layers used in the 1D2D branch')
    parser.add_argument('--one_d_two_d_dropout', type=float, default=0.25,
        help='dropout rate inside the 1D2D branch')
    parser.add_argument('--no_one_d_two_d_protein_2d', action='store_true',
        help='disable the protein CA graph path inside the 1D2D branch')
    parser.add_argument('--one_d_two_d_fc_dims', type=int, nargs='+', default=[1024, 128],
        help='FC projection dimensions for the 1D2D branch before top-level concat')

    # Top model parameters
    parser.add_argument('--mlp_dims', type=int, nargs='+', default=[1024, 512],
        help='top MLP layers dimensions')
    parser.add_argument('--mlp_dropout', type=float, default=0.25,
        help='dropout rate in top MLP')

    # molecular dropout (DockTDeep-style)
    parser.add_argument('--use_molecular_dropout', action='store_true',
        help='enable DockTDeep-style molecular dropout during training')
    parser.add_argument('--molecular_dropout_p', type=float, default=0.06,
        help='per-sample probability a drop fires (DockTDeep used 0.06)')
    parser.add_argument('--molecular_dropout_anchor', type=float, default=0.0,
        help='target for dropped samples; raw pKd -> 0.0 = no binding')
    parser.add_argument('--molecular_dropout_mode', default='complex',
        choices=['complex', 'protein', 'ligand'],
        help='complex=50/50 protein-or-ligand (faithful); else always that side')
    # uncertainty parameters
    parser.add_argument('--uncertainty', action='store_true',
        help='estimate uncertainty')
    parser.add_argument('--recalibrate', action='store_true',
        help='recalibrate uncertainty')
    parser.add_argument('--heteroscedastic', action='store_true',
        help='enable heteroscedastic Gaussian NLL head (aleatoric uncertainty)')
    parser.add_argument('--nll_warmup_epochs', type=int, default=10,
        help='number of MSE warm-up epochs before switching to Gaussian NLL')
    parser.add_argument('--nll_logvar_min', type=float, default=-7.0,
        help='lower clamp bound on predicted log-variance')
    parser.add_argument('--nll_logvar_max', type=float, default=7.0,
        help='upper clamp bound on predicted log-variance')

    # Training parameters
    parser.add_argument('--n_ensembles', type=int, default=1,
        help='number of ensembles')
    parser.add_argument('--batch_size', type=int, default=128,
        help='batch size')
    parser.add_argument('--n_epochs', type=int, default=500,
        help='number of epochs')
    parser.add_argument('--patience', action='store', type=int,
        help='patience for early stopping')
    parser.add_argument('--eval_freq', type=int, default=1,
        help='evaluation frequency')
    parser.add_argument('--test_freq', type=int,
        help='test frequency')
    parser.add_argument('--lr', type=float, default=0.0005,
        help='learning rate')
    parser.add_argument('--monitor_metric', default='pearson',
        help='validation metric to monitor for deciding best checkpoint')
    parser.add_argument('--parallel', action='store_true',
        help='run ensembles in parallel on multiple GPUs')

    # Save parameters
    parser.add_argument('--output_dir', action='store', default='../output', help='output folder')
    parser.add_argument('--save_log', action='store_true', default=False, help='save log file')
    parser.add_argument('--save_checkpoint', action='store_true', default=False, help='save checkpoint')
    parser.add_argument('--save_prediction', action='store_true', default=False, help='save prediction')
